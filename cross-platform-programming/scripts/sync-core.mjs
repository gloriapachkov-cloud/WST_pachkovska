// One maintained source: packages/core/index.cjs.
// Generate browser-compatible ESM without duplicating business logic by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'packages/core/index.cjs'), 'utf8');
const match = source.match(/module\.exports\s*=\s*\{([^}]+)\};?\s*$/);
if (!match) throw new Error('Cannot find core module.exports object');
const names = match[1].split(',').map(s => s.trim()).filter(Boolean);
if (!names.every(n => /^[A-Za-z_$][\w$]*$/.test(n))) throw new Error('Unexpected export names');
const body = source.slice(0, match.index).replace(/^\s*["']use strict["'];?/, '');
const generated = '// AUTO-GENERATED by scripts/sync-core.mjs. Do not edit directly.\n' + body + '\nexport { ' + names.join(', ') + ' };\n';
writeFileSync(resolve(root, 'packages/core/index.mjs'), generated);
console.log('Synced core ESM exports:', names.length);
